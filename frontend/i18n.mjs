export function isSupportedLang(value) {
    return value === "id" || value === "en";
}

function detectInitialLang() {
    const stored = typeof localStorage !== "undefined" ? localStorage.getItem("aae_lang") : null;
    if (isSupportedLang(stored)) {
        return stored;
    }
    // English is the default; visitors can switch to Indonesian anytime.
    return DEFAULT_LANG;
}

let currentLang = detectInitialLang();

export function getCurrentLang() {
    return currentLang;
}

export function setLang(lang) {
    currentLang = lang;
    if (typeof localStorage !== "undefined") {
        localStorage.setItem("aae_lang", lang);
    }
    if (typeof document !== "undefined" && document.documentElement) {
        document.documentElement.lang = lang;
    }
}

export function t(key, params = {}) {
    const dict = LANG[currentLang] || LANG[DEFAULT_LANG];
    let text = dict[key] || LANG[DEFAULT_LANG][key] || key;
    return text.replace(/\{\{(\w+)\}\}/g, (match, name) => {
        return params[name] !== undefined ? params[name] : match;
    });
}
